#!/usr/bin/env python3
"""Write canonical linux-firmware package members from families.toml.

Usage: gen-members.py [--out DIR] [--check]

Each member globs its family's tree out of the build stage and publishes a
revision-exact legacy provide/replacement for existing Peios consumers. The
files are generated rather than hand-written so a family cannot exist in one
place and not the other: `pekit gen members` regenerates them, and the gen
target's verify_command runs this with --check as the drift gate.
"""
import argparse, os, sys, tomllib

HEADER = """# GENERATED by tools/gen-members.py from families.toml — do not edit.
# Regenerate with `pekit gen members`.
"""


def render(name, fam):
    lic_class = fam.get("license_class", "firmware")
    canonical = f"org.kernel.linux-firmware-{name}"
    legacy = f"firmware-{name}"
    lines = [HEADER, "[package]",
             f'name          = "{canonical}"',
             f'description   = "{fam["description"]}"',
             f'license       = "{fam["license"]}"',
             f'license_class = "{lic_class}"',
             "", "[provides]",
             f'"{legacy}" = "{{{{version}}}}-3"',
             "", "[replaces]",
             f'"{legacy}" = "<= {{{{version}}}}-2"',
             "", "[files]",
             f'":family/{name}/usr/lib/firmware/**"   = "usr/lib/firmware"',
             f'":family/{name}/usr/share/licenses/**" = "usr/share/licenses"',
             ""]
    return "\n".join(lines)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--families", default="families.toml")
    ap.add_argument("--out", default="packages.pekit")
    ap.add_argument("--check", action="store_true")
    args = ap.parse_args()
    with open(args.families, "rb") as fh:
        doc = tomllib.load(fh)
    want = {f"org.kernel.linux-firmware-{n}.package.pekit.toml": render(n, f)
            for n, f in doc["family"].items()}
    have = {f for f in os.listdir(args.out)
            if f.endswith(".package.pekit.toml") and f != "package.pekit.toml"}
    stale = []
    for fname, text in want.items():
        path = os.path.join(args.out, fname)
        if not os.path.exists(path) or open(path).read() != text:
            stale.append(fname)
            if not args.check:
                with open(path, "w") as fh:
                    fh.write(text)
    for fname in sorted(have - set(want)):
        stale.append(fname + " (no such family)")
        if not args.check:
            os.unlink(os.path.join(args.out, fname))
    if args.check and stale:
        print("gen-members: package members are out of date with families.toml — run `pekit gen members`:",
              file=sys.stderr)
        for s in stale:
            print("  " + s, file=sys.stderr)
        sys.exit(1)
    print(f"gen-members: {len(want)} members {'in sync' if args.check else 'written'}")


if __name__ == "__main__":
    main()
